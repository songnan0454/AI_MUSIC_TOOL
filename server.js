// 歌词转同音字 API
app.post('/homophone', (req, res) => {
  const { lyrics, ratio = 0.3 } = req.body;
  if (!lyrics) {
    return res.status(400).json({ error: '请提供歌词内容' });
  }

  const isChinese = (c) => /[一-龥]/.test(c);

  // 获取所有中文字符的位置
  const chineseChars = [];
  for (let i = 0; i < lyrics.length; i++) {
    if (isChinese(lyrics[i])) {
      chineseChars.push({ index: i, char: lyrics[i] });
    }
  }

  // 随机选择要转换的字（按比例）
  const numToConvert = Math.floor(chineseChars.length * ratio);
  const shuffled = [...chineseChars].sort(() => Math.random() - 0.5);
  const charsToConvert = shuffled.slice(0, numToConvert);

  // 转换为同音字
  const result = lyrics.split('');
  for (const { index, char } of charsToConvert) {
    const py = pinyin(char, { toneType: 'none' });
    const homophones = homophoneMap[py];

    if (homophones && homophones.length > 1) {
      // 过滤掉原字，选择其他同音字
      const alternatives = homophones.filter(h => h !== char);
      if (alternatives.length > 0) {
        // 随机选择一个同音字
        const newChar = alternatives[Math.floor(Math.random() * alternatives.length)];
        result[index] = newChar;
      }
    }
  }

  res.json({
    success: true,
    original: lyrics,
    converted: result.join(''),
    convertedCount: charsToConvert.length,
    totalChinese: chineseChars.length
  });
});

// 歌词转拼音 API
app.post('/pinyin', (req, res) => {
  const { lyrics } = req.body;
  if (!lyrics) {
    return res.status(400).json({ error: '请提供歌词内容' });
  }

  const isChinese = (c) => /[一-龥]/.test(c);
  const isEnglish = (c) => ('A' <= c && c <= 'Z') || ('a' <= c && c <= 'z');

  const result = [];
  let i = 0;
  while (i < lyrics.length) {
    const char = lyrics[i];

    if (char === '\n') {
      result.push('\n');
    } else if (char === ' ') {
      result.push(' ');
    } else if (char === '（') {
      result.push('(');
    } else if (char === '）') {
      result.push(')');
    } else if (isChinese(char)) {
      // 中文转拼音，前面如果不是空格或换行或括号则加空格
      if (result.length > 0 && !['\n', ' ', '('].includes(result[result.length - 1])) {
        result.push(' ');
      }
      result.push(pinyin(char, { toneType: 'none' }));
    } else if (isEnglish(char)) {
      // 收集连续英文
      let word = char;
      while (i + 1 < lyrics.length && isEnglish(lyrics[i + 1])) {
        i++;
        word += lyrics[i];
      }
      // 前面如果不是空格或换行或括号则加空格
      if (result.length > 0 && !['\n', ' ', '('].includes(result[result.length - 1])) {
        result.push(' ');
      }
      result.push(word);
    } else {
      result.push(char);
    }
    i++;
  }

  let output = result.join('');
  // 清理多余空格
  output = output.replace(/ +/g, ' ').replace(/ \n/g, '\n');

  res.json({ success: true, pinyin: output });
});

