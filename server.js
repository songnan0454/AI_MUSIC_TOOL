const express = require('express');
const multer = require('multer');
const ffmpeg = require('fluent-ffmpeg');
const path = require('path');
const fs = require('fs');
const { v4: uuidv4 } = require('uuid');
const { pinyin } = require('pinyin-pro');
const mm = require('music-metadata');

const app = express();
const PORT = 3000;

// 创建必要的目录
const dirs = ['uploads', 'processed', 'output'];
dirs.forEach(dir => {
  if (!fs.existsSync(dir)) {
    fs.mkdirSync(dir, { recursive: true });
  }
});

// 配置 multer 用于文件上传
const storage = multer.diskStorage({
  destination: (req, file, cb) => {
    cb(null, 'uploads/');
  },
  filename: (req, file, cb) => {
    const sessionId = uuidv4();
    req.sessionId = sessionId;
    // 正确处理中文文件名
    const originalname = Buffer.from(file.originalname, 'latin1').toString('utf8');
    file.originalname = originalname;
    cb(null, `${sessionId}-${originalname}`);
  }
});

const upload = multer({
  storage,
  fileFilter: (req, file, cb) => {
    const allowedAudio = ['.mp3', '.wav', '.m4a', '.flac'];
    const allowedVideo = ['.mp4', '.mov', '.avi', '.mkv', '.webm', '.flv'];
    const ext = path.extname(file.originalname).toLowerCase();
    if (allowedAudio.includes(ext) || allowedVideo.includes(ext)) {
      cb(null, true);
    } else {
      cb(new Error('只支持音频文件 (mp3, wav, m4a, flac) 或视频文件 (mp4, mov, avi, mkv, webm, flv)'));
    }
  },
  limits: { fileSize: 500 * 1024 * 1024 } // 500MB 限制
});

